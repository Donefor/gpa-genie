export interface CourseRecord {
  courseNo: string;
  course: string;
  term: string;
  /** Calendar year the period ran in. */
  year: number;
  /** Study period, 1-4. */
  period: number;
  registered: number;
  passedMainExam: number | null;
  passedAtPresent: number | null;
  /** Share of passing students per band, or null when not graded on a scale. */
  distribution: Record<StatGrade, number> | null;
  /** False when the round appears in the export with no results yet. */
  reported: boolean;
}

const toRecord = (row: StatRow): CourseRecord => {
  const [courseNo, course, term, registered, passedMainExam, passedAtPresent, e, vg, g, p, reported] =
    row;
  return {
    courseNo,
    course,
    term,
    year: 2000 + Number(term.slice(0, 2)),
    period: Number(term.slice(2)),
    registered,
    passedMainExam,
    passedAtPresent,
    distribution:
      e === null ? null : { Excellent: e, 'Very Good': vg ?? 0, Good: g ?? 0, Pass: p ?? 0 },
    reported: reported === 1,
  };
};

/** Every deduplicated round, including the handful with no results yet. */
export const ALL_RECORDS: CourseRecord[] = RAW_STATS.map(toRecord);

/** Rounds that actually reported results — the basis for every statistic. */
export const COURSE_RECORDS: CourseRecord[] = ALL_RECORDS.filter((record) => record.reported);
