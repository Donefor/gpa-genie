export interface CatalogueCourse {
  courseNo: string;
  name: string;
  credits: number;
  /** False when the credits are the fallback rather than published. */
  creditsKnown: boolean;
  rounds: number;
  registrations: number;
}

const toCourse = ([courseNo, name, ects, rounds, registrations]: CatalogueRow): CatalogueCourse => ({
  courseNo,
  name,
  credits: ects ?? DEFAULT_ELECTIVE_CREDITS,
  creditsKnown: ects !== null,
  rounds,
  registrations,
});

/** Everything in the export, including the non-credit entries. */
export const ALL_CATALOGUE: CatalogueCourse[] = CATALOGUE_ROWS.map(toCourse);

/**
 * What can fill an elective slot. Courses published at 0 ECTS — programme
 * channels, reflection series, professional tracks — are left out: they carry
 * no weight in an average and are not electives anyone chooses.
 */
export const CATALOGUE: CatalogueCourse[] = ALL_CATALOGUE.filter((c) => c.credits > 0);

const BY_NO = new Map(ALL_CATALOGUE.map((c) => [c.courseNo, c]));
export const catalogueCourse = (courseNo: string) => BY_NO.get(courseNo);
